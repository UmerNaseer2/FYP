// generate-sql-db-name-clashes: scripts that reuse a name the target still
// has, run on a real PostgreSQL.
//
// Tables, views, sequences and indexes share one set of names in a schema, and
// a primary key, unique or exclusion constraint has an index of the same name.
// So the script can want a name that the target still uses for something else:
// a key that moves to another table, a table renamed in the source whose key
// and sequence kept their old names, a loose sequence holding the name that a
// column's own sequence should have. The client's tester met the first kind on
// a renamed table: relation "b_pkey" already exists.
//
// Each case builds a source and a target schema and goes the whole way round:
//
//   the safe-mode script runs (and is undone)
//   -> the full script runs, then runs a second time without harm
//   -> the rows the case inserts afterwards go in (the sequences still work)
//   -> the target is level with the source
//   -> the rollback runs and the target is level with where it started
//
// It needs a Postgres it may create and drop databases and two roles in, so it
// runs only when TEST_DATABASE_URL is set, like tests/generate-sql-db.test.ts.
