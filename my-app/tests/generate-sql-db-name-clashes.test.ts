function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

describeWithDatabase("scripts that reuse a name the target still has, on a real PostgreSQL", () => {
  let server: Client;
  let source: Client;
  let target: Client;
  let sourceConfig: ClientConfig;
  let targetConfig: ClientConfig;
  const databases: string[] = [];

  function configFor(database: string): ClientConfig {
    const url = new URL(testUrl);
    return {
      host: url.hostname,
      port: Number(url.port || 5432),
      user: decodeURIComponent(url.username),
      password: decodeURIComponent(url.password),
      database,
    };
  }

  /** Empties the schema in one database and builds it again from `ddl`. */
  async function build(db: Client, ddl: string, owner?: string): Promise<void> {
    await db.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE; CREATE SCHEMA ${SCHEMA};`);
    if (owner) await db.query(`GRANT ALL ON SCHEMA ${SCHEMA} TO ${owner}`);
    const role = owner ? `SET LOCAL ROLE ${owner};` : "";
    await db.query(`BEGIN; SET LOCAL search_path TO ${SCHEMA}; ${role} ${ddl}; COMMIT;`);
  }

  async function read(config: ClientConfig): Promise<SchemaSnapshot> {
    const answer = await fetchSchemaSnapshot(config, SCHEMA);
    if (!answer.ok) throw new Error(`Could not read the schema: ${answer.error}`);
    return answer.data;
  }

  /** What a script would still have to run to make `to` look like `from`. */
  function stillToDo(from: SchemaSnapshot, to: SchemaSnapshot): string[] {
    const script = generateMigration(compareSchemas(from, to), { allowDataLoss: true });
    return statementsThatRun(script).map((statement) => statement.sql);
  }

  /**
   * Runs `scripts` one after another on the target in one transaction, the way
   * Deploy does, then commits, or rolls back when `keep` is false.
   */
  async function runOnTarget(scripts: string[], runAs: string | undefined, keep = true): Promise<void> {
    const role = runAs ? `SET LOCAL ROLE ${runAs};` : "";
    await target.query(`BEGIN; SET LOCAL search_path TO ${SCHEMA}; ${role}`);
    for (const [index, script] of scripts.entries()) {
      try {
        await target.query(script);
      } catch (error) {
        await target.query("ROLLBACK");
        const message = error instanceof Error ? error.message : String(error);
        throw new Error(`PostgreSQL refused part ${index + 1}: ${message}\n\n${script}`);
      }
    }
    await target.query(keep ? "COMMIT" : "ROLLBACK");
  }

  beforeAll(async () => {
    const baseName = decodeURIComponent(new URL(testUrl).pathname.slice(1));
    if (!/test/i.test(baseName)) {
      throw new Error(
        `TEST_DATABASE_URL names "${baseName}". These tests create and drop databases, ` +
          `so they only run against one whose name contains "test".`
      );
    }
    server = new Client({ connectionString: testUrl });
    await server.connect();
    for (const role of ROLES) {
      await server.query(
        `DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') ` +
          `THEN CREATE ROLE ${role} NOLOGIN; END IF; END $$`
      );
    }
    for (const side of ["source", "target"]) {
      const name = `${baseName}_clash_${side}`;
      await server.query(`DROP DATABASE IF EXISTS ${quoteIdent(name)} WITH (FORCE)`);
      await server.query(`CREATE DATABASE ${quoteIdent(name)}`);
      databases.push(name);
    }
    sourceConfig = configFor(databases[0]);
    targetConfig = configFor(databases[1]);
    source = new Client(sourceConfig);
    target = new Client(targetConfig);
    await source.connect();
    await target.connect();
  }, SETUP);

  afterAll(async () => {
    if (sourceConfig) await getPoolForConfig(sourceConfig).end();
    if (targetConfig) await getPoolForConfig(targetConfig).end();
    await source?.end();
    await target?.end();
    for (const name of databases) {
      await server.query(`DROP DATABASE IF EXISTS ${quoteIdent(name)} WITH (FORCE)`);
    }
    // The roles own nothing once both databases are gone.
    for (const role of ROLES) await server?.query(`DROP ROLE IF EXISTS ${role}`);
    await server?.end();
  }, SETUP);

  it.each(CASES)(
    "%s",
    async (_label, sourceDdl, targetDdl, options = {}) => {
      await build(source, sourceDdl, options.owner);
      await build(target, targetDdl, options.owner);
      const wanted = await read(sourceConfig);
      const before = await read(targetConfig);
      const report = compareSchemas(wanted, before);

      // Safe mode holds back what would lose data, and still has to run.
      const safe = renderMigrationScript(generateMigration(report, { allowDataLoss: false }));
      await runOnTarget([safe], options.runAs, false);

      // The full script, a second run of it, and the rows the case adds after.
      const armed = renderMigrationScript(generateMigration(report, { allowDataLoss: true }));
      await runOnTarget([armed, armed, ...(options.after ? [options.after] : [])], options.runAs);
      expect(stillToDo(wanted, await read(targetConfig))).toEqual([]);

      await runOnTarget(
        [renderRollbackScript(generateRollback(report, { allowDataLoss: true }))],
        options.runAs
      );
      expect(stillToDo(before, await read(targetConfig))).toEqual([]);

      // A grant that includes TRUNCATE empties nothing.
      if (/TRUNCATE/.test(sourceDdl)) expect(findRowDestroyingStatements(armed)).toEqual([]);
    },
    SLOW
  );
});
