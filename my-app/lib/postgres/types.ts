import type {
  CollationSnapshot,
  ExtensionElsewhere,
  ExtensionSnapshot,
  PrivilegeSnapshot,
  RoutineSnapshot,
  SequenceOptions,
  SequenceSnapshot,
  TypeSnapshot,
  ViewSnapshot,
} from "./object-types";

