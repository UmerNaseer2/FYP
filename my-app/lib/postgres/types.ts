/**
 * The snapshot types, part one: a comparison target, a table and everything
 * that hangs off it (columns, constraints, indexes, triggers, row security,
 * partitioning), and SchemaSnapshot itself.
 *
 * The types for the other objects a schema holds (views, sequences, types,
 * collations, routines, extensions, privileges) are in object-types.ts and
 * re-exported here, so every file in this folder imports its types from
 * "./types".
 */
