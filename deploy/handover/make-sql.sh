#!/usr/bin/env bash
# Regenerates sql/02-schema-studio-tables.sql from an app image.
#
#   deploy/handover/make-sql.sh [image]     (default: schema-studio-app:handover)
#
# Run it after any change to the app's tables (lib/db/models, lib/db/bootstrap)
# and commit the result. CI runs it too and fails when the committed file is
# out of date.
#
# How: it starts a throwaway PostgreSQL 16 container, runs sql/01 in it the way
# SETUP-GUIDE.md does, starts the app image against it so the app creates its
# own tables, waits for that to finish, and dumps the structure with
# PostgreSQL 16's own pg_dump. The dump is plain SQL with no owner and no
# privilege lines, so it loads as the schema_studio login on PostgreSQL 16 or
# newer. Everything it starts is removed again at the end, even on failure.
#
# Needs: Docker, and the image built or loaded on this machine.

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
image="${1:-schema-studio-app:handover}"
out="$here/sql/02-schema-studio-tables.sql"
pg_image="postgres:16-alpine"
tag="ss-make-sql-$$"
db="$tag-db"
app="$tag-app"
# lib/db/bootstrap.ts holds this advisory lock for the whole of table creation.
bootstrap_lock=7365786101

cleanup() {
  docker rm -f "$app" "$db" >/dev/null 2>&1 || true
  docker network rm "$tag" >/dev/null 2>&1 || true
}
trap cleanup EXIT

if ! docker image inspect "$image" >/dev/null 2>&1; then
  echo "No image called $image here. Build it (docker build -t $image my-app) or docker load it first." >&2
  exit 1
fi

echo "Starting a throwaway PostgreSQL 16"
docker network create "$tag" >/dev/null
docker run -d --name "$db" --network "$tag" \
  -e POSTGRES_PASSWORD="$(openssl rand -hex 16)" "$pg_image" >/dev/null

# Over TCP on purpose: during its first start the image runs a temporary server
# on the socket only, and that one is about to stop.
for _ in $(seq 90); do
  if docker exec "$db" pg_isready -q -h 127.0.0.1 -U postgres; then break; fi
  sleep 1
done
docker exec "$db" pg_isready -q -h 127.0.0.1 -U postgres

echo "Running sql/01 as the guide does"
password="$(openssl rand -hex 24)"
docker exec -i -e SS_DB_PASSWORD="$password" "$db" \
  psql -q -U postgres -d postgres -v ON_ERROR_STOP=1 -f - \
  < "$here/sql/01-database-and-login.sql" >/dev/null

echo "Letting $image create its tables"
# Placeholder sign-in values: the app only needs them to start, and nobody
# signs in here. The host is a container name, not localhost, so SSL is
# switched off in the address.
docker run -d --name "$app" --network "$tag" \
  -e DATABASE_URL_A="postgres://schema_studio:$password@$db:5432/schema_studio?sslmode=disable" \
  -e NEXTAUTH_SECRET="$(openssl rand -hex 32)" \
  -e APP_ENCRYPTION_KEY="$(openssl rand -hex 32)" \
  -e AZURE_AD_CLIENT_ID=make-sql \
  -e AZURE_AD_CLIENT_SECRET=make-sql \
  -e AZURE_AD_TENANT_ID=make-sql \
  -e AUTH_URL=http://localhost:3000 \
  "$image" >/dev/null

# Finished means: the organizations table exists (created early, under the
# lock) and the lock is free again (released only after the last step).
finished=""
for _ in $(seq 180); do
  finished="$(docker exec "$db" psql -U postgres -d schema_studio -tAq -c \
    "SELECT to_regclass('public.organizations') IS NOT NULL AND pg_try_advisory_xact_lock($bootstrap_lock)" \
    2>/dev/null || true)"
  [ "$finished" = "t" ] && break
  if [ "$(docker inspect -f '{{.State.Running}}' "$app")" != "true" ]; then
    echo "The app stopped before its tables were made. Its output:" >&2
    docker logs "$app" >&2 || true
    exit 1
  fi
  sleep 1
done
if [ "$finished" != "t" ]; then
  echo "The app did not finish making its tables within 3 minutes. Its output:" >&2
  docker logs "$app" >&2 || true
  exit 1
fi
# The scheduler's first tick is what made the tables; a failure there is
# logged as "tick failed".
if docker logs "$app" 2>&1 | grep -q "tick failed"; then
  echo "The app reported a problem making its tables:" >&2
  docker logs "$app" >&2 || true
  exit 1
fi
docker stop -t 10 "$app" >/dev/null

echo "Dumping with PostgreSQL 16's pg_dump"
dump="$(mktemp)"
trap 'rm -f "$dump"; cleanup' EXIT
docker exec "$db" pg_dump -U postgres -d schema_studio \
  --schema-only --no-owner --no-privileges --no-comments --quote-all-identifiers \
  > "$dump"

# Plain SQL for any psql and for the Supabase SQL editor:
#   * \restrict and \unrestrict are psql-only lines newer pg_dump releases add;
#   * the version lines change with every PostgreSQL patch release and would
#     make CI's "is this file up to date" check fail for no reason.
{
  cat <<'HEADER'
-- Schema Studio: the app's own tables, for PostgreSQL 16 (or newer).
--
-- Generated by deploy/handover/make-sql.sh from the app image. Do not edit it
-- by hand: change the app, then run that script again.
--
-- Load it once, after sql/01-database-and-login.sql, as the schema_studio
-- login, so that login owns every table (the app changes its own tables when
-- a new version adds a column, and only an owner may):
--
--   PGPASSWORD="$SS_DB_PASSWORD" psql -h 127.0.0.1 -U schema_studio \
--     -d schema_studio -v ON_ERROR_STOP=1 -f sql/02-schema-studio-tables.sql
--
-- This is structure only. On its first start the app adds the rows it needs
-- itself: the default organization and its built-in roles. The first person
-- who signs in becomes that organization's Admin.
--
-- Loading this file is optional: on an empty database the app creates
-- exactly these tables itself at first start. It is here so you can read and
-- review every table before the app runs, and create them yourself.

HEADER
  grep -vE '^\\(un)?restrict |^-- Dumped (from database|by pg_dump) version ' "$dump"
} > "$out"

tables="$(grep -c '^CREATE TABLE ' "$out" || true)"
echo "Wrote ${out#"$here"/} ($tables tables)"
